-- ========================================================
-- LoadSecure: Configuração do Banco de Dados no Supabase (PostgreSQL)
-- ========================================================

CREATE TABLE IF NOT EXISTS companies (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    name_key TEXT NOT NULL UNIQUE,
    join_code TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES companies(id),
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    role TEXT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS users_company ON users(company_id);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id),
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS records (
    company_id TEXT NOT NULL REFERENCES companies(id),
    kind TEXT NOT NULL,
    id TEXT NOT NULL,
    data TEXT NOT NULL,
    revision INTEGER NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (company_id, kind, id)
);

CREATE TABLE IF NOT EXISTS login_attempts (
    key TEXT PRIMARY KEY,
    count INTEGER NOT NULL,
    since BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS _migrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    applied_at BIGINT NOT NULL
);

-- ========================================================
-- Permissões / Row Level Security (RLS)
-- ========================================================
-- Para permitir que as operações de leitura e gravação funcionem
-- via chave da API (Publishable/Anon key) sem erro 42501:
ALTER TABLE companies DISABLE ROW LEVEL SECURITY;
ALTER TABLE users DISABLE ROW LEVEL SECURITY;
ALTER TABLE sessions DISABLE ROW LEVEL SECURITY;
ALTER TABLE records DISABLE ROW LEVEL SECURITY;
ALTER TABLE login_attempts DISABLE ROW LEVEL SECURITY;
ALTER TABLE _migrations DISABLE ROW LEVEL SECURITY;
